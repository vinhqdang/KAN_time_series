"""Builds EXTENSION_RESULTS.md from the raw CSVs (post-acceptance extension, X1-X5)."""
import os, glob
import numpy as np, pandas as pd
from scipy.stats import wilcoxon
ER = os.path.join(os.path.dirname(__file__), "..", "experimental_results"); out = []
P = lambda *a: out.append(" ".join(str(x) for x in a))


def md(df): return df.to_markdown() if hasattr(df, "to_markdown") else df.to_string()


P("# SPADE extension (post-acceptance): results of the five follow-up directions\n")
P("All numbers are generated by `scripts/build_extension_report.py` from `experimental_results/`. Protocols (seeds, selection rules) are in each script's docstring; candidates were chosen on validation seeds/inner splits disjoint from the evaluation data, except where marked *post-hoc*.\n")

# X1
d = pd.read_csv(os.path.join(ER, "x1_final_raw.csv")); v = pd.read_csv(os.path.join(ER, "x1_validation_raw.csv"))
P("## X1. Sparsity / shrinkage fix: SPADE-AB (adaptive group-lasso, averaged over 5 half-sample fits)\n")
P("Validation seeds 200-219 (d=6,10), 200-204 (d=20), mean AUROC:\n")
P(md(v.groupby(["d", "variant"]).auroc.mean().unstack().round(3)))
P("\nFrozen candidate = `adaptive_boot` (best at every width). Fresh seeds 300-319 / 300-304 (AUROC mean; paired Wilcoxon on all 45 runs):\n")
q = d[d.part == "fresh"].pivot_table(index=["d", "seed"], columns="method", values="auroc"); x = q["SPADE-AB"] - q["SPADE"]
P(md(d[d.part == "fresh"].groupby(["d", "method"]).agg(auroc=("auroc", "mean"), auprc=("auprc", "mean"), f1=("f1", "mean")).round(3)))
P(f"\nPooled paired difference AB - base = {x.mean():+.3f} AUROC (wins {int((x>0).sum())}, ties {int((x==0).sum())}, n={len(x)}, Wilcoxon p={wilcoxon(x[x!=0]).pvalue:.4f}).\n")
P("Official reporting seeds in this environment (note: base SPADE re-run here gives d=10 AUROC 0.892, not the published 0.926: a library-version effect, see caveats):\n")
P(md(d[d.part == "official"].groupby(["d", "method"]).auroc.mean().unstack().round(3)))
r = pd.read_csv(os.path.join(ER, "instdag_raw.csv"))
for m in ["NoGAM", "SCORE"]:
    P(f"- stored {m} on official seeds: " + ", ".join(f"d={dd}: {r[(r.method==m)&(r.d==dd)].auroc.mean():.3f}" for dd in (6, 10, 20)))
rw = pd.read_csv(os.path.join(ER, "realworld_spade_ab.csv"))
P("\n*Post-hoc* (hourly bike sharing and Beijing, common 2,000-row sample, BK-AUROC, 6 resamples; published linear NOTEARS: 0.649 and 0.669):\n")
P(md(rw.groupby(["dataset", "method"]).bk_auroc.agg(["mean", "std"]).round(3)))

# X2
s = pd.read_csv(os.path.join(ER, "sachs_raw.csv")); s = s[s.status == "ok"]; p = s[s.part == "primary"]
P("\n## X2. Real ground truth: Sachs protein-signalling network (11 nodes, 18 true edges, chance AUPRC 0.164)\n")
P("10 random subsamples of 2,000 cells; mean over resamples (std in brackets for AUROC):\n")
g = p.groupby("method").agg(auroc=("auroc", "mean"), auroc_sd=("auroc", "std"), auprc=("auprc", "mean"), f1=("f1", "mean"), hits_top18=("hits", "mean"), shd=("shd", "mean")).sort_values("auroc", ascending=False).round(3)
P(md(g))
q = p.pivot(index="resample", columns="method", values="auroc")
P("\nPaired Wilcoxon of SPADE-AB vs each method (10 resamples): " + "; ".join(f"{m}: {int((q['SPADE-adaptive_boot']-q[m]>0).sum())}/10 wins, p={wilcoxon(q['SPADE-adaptive_boot']-q[m]).pvalue:.3f}" for m in q.columns if m != "SPADE-adaptive_boot") + ".\n")
f = s[s.part == "full"]; P("Full data (n=7,466, one run):\n"); P(md(f.set_index("method")[["auroc", "auprc", "hits", "shd"]].round(3)))
P("\nAll methods are weak in absolute terms (top-18 hits <= 7 of 18), as is typical for Sachs; SPADE-AB is the best of those tested, not accurate.\n")

# X3
t = pd.read_csv(os.path.join(ER, "x3_fidelity_raw.csv")); t["nonlinear"] = t.linear_oracle_r2 < 0.5
P("## X3. Interpretability, measured: how well does the learned edge function recover the true mechanism?\n")
P("Fresh seeds 400-419 (d=6 and 10). `found` = true edge ranked within the top-|E| scored edges (uses the true edge count; same rule for all). R2 = best affine fit of learned curve to true curve; class = increasing/decreasing/non-monotone agreement.\n")
for lab, qq in [("Found edges, all", t[t.found]), ("Found edges, strongly non-linear (a line explains <50%: sin, quadratic)", t[t.found & t.nonlinear])]:
    P(f"\n{lab}:\n"); P(md(qq.groupby(["d", "method"]).agg(r2=("r2", "mean"), class_agree=("cls_ok", "mean"), n_found=("r2", "size")).round(3)))
P("\n`SPADE` = raw fitted splines; `SPADE-2stage` = same structure, curves from a smoothness-penalized (second-difference, 0.01) refit on the retained edges: the raw curves wiggle (class agreement 0.12-0.25), the 2-stage curves do not (0.93-0.94) at no cost to structure recovery. `MLP-edge` finds only 3-4 of the strongly non-linear edges versus 15-16 for SPADE.\n")

# X4
P("## X4. Scale (fresh seeds 600-602, n=3,000)\n")
rows = []
for dd in (50, 100, 200):
    fp = os.path.join(ER, f"x4_final_d{dd}.csv")
    if os.path.exists(fp): rows.append(pd.read_csv(fp))
x4 = pd.concat(rows); sp = os.path.join(ER, "x4_score.csv")
if os.path.exists(sp): x4 = pd.concat([x4, pd.read_csv(sp)])
P(md(x4.groupby(["d", "method"]).agg(auroc=("auroc", "mean"), auroc_sd=("auroc", "std"), auprc=("auprc", "mean"), n=("auroc", "size")).round(3)))
P("\nRule chosen on validation seeds 500-502: lambda_g = min(0.01, 0.2/d) and per-node parent screening (ExtraTrees, K=15). Wall-clock times are omitted: jobs shared a 4-core machine. GOLEM and NOTEARS-MLP were run only at d=50 (>15 min per fit), SCORE only where it finished; DAGMA-nonlinear, GraN-DAG and NoGAM could not be run at d>=100.\n")

# X5
f5 = pd.read_csv(os.path.join(ER, "x5_final_raw.csv")); b5 = pd.read_csv(os.path.join(ER, "x5b_beijing_raw.csv"))
P("## X5. Forecasting\n"); P("Financial panel, test folds, seeds 42-44 (all models re-run in this environment; MSE in raw price units):\n")
P(md(f5.groupby("model").agg(mse=("mse", "mean"), sd=("mse", "std"), mae=("mae", "mean")).sort_values("mse").round(4)))
P("\nBeijing weather + PM2.5 (pre-registered, nothing tuned on it; MSE in z-scored units):\n")
P(md(b5.groupby("model").agg(mse=("mse", "mean"), n=("mse", "size")).sort_values("mse").round(4)))
P("\n**Finding.** A naive last-value forecast is at least as good as every learned model on both data sets (0.0177 vs 0.0245 best deep model on finance). The published comparison omitted this baseline. SPADE-fast (residual + group-lasso, cached bases, 300 epochs) matches the naive forecast and is the best learned model on both, and trains in seconds instead of minutes, but it does not beat naive.\n")
open(os.path.join(os.path.dirname(__file__), "..", "EXTENSION_RESULTS.md"), "w").write("\n".join(out)); print("written")
