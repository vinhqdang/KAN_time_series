"""
Turn honest_*.csv benchmark outputs into LaTeX table bodies + summary figures.
Robust to partial data (uses whatever configs have completed).

Outputs:
  manuscript/figures/tab_causal.tex       (causal discovery, overall + by regime)
  manuscript/figures/tab_causal_stats.tex (Wilcoxon paired tests)
  manuscript/figures/tab_forecast.tex     (forecasting)
  manuscript/figures/cdkan_sota_comprehensive_results.png
  manuscript/figures/cdkan_sota_heatmap.png
  experimental_results/NUMBERS.json        (all headline numbers for the text)
"""
import os, json, sys
import numpy as np, pandas as pd
import matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt

RES = "experimental_results"
FIG = "manuscript/figures"
os.makedirs(FIG, exist_ok=True)
NUM = {}

ORDER = ["CD-KAN", "GC-KAN+ALM", "GC-KAN", "PCMCI", "VarLiNGAM",
         "VAR-Lasso", "NOTEARS", "GOLEM", "Correlation"]


def load_causal():
    df = pd.read_csv(os.path.join(RES, "honest_causal_raw.csv"))
    # Back-compat: earlier runs logged two CD-KAN readouts; keep the prob one.
    if "CD-KAN(prob)" in set(df.method):
        df = df[df.method != "CD-KAN"].copy()
        df.loc[df.method == "CD-KAN(prob)", "method"] = "CD-KAN"
    return df


def fmt(m, s):
    if pd.isna(s):
        return f"{m:.3f}"
    return f"{m:.3f}$\\pm${s:.3f}"


def agg_table(df, regime=None):
    d = df if regime is None else df[df.kind == regime]
    g = d.groupby("method").agg(
        f1m=("f1", "mean"), f1s=("f1", "std"),
        aum=("auroc", "mean"), aus=("auroc", "std"),
        apm=("auprc", "mean"), aps=("auprc", "std"),
        shdm=("shd", "mean"), tm=("time_s", "mean"),
    )
    return g


def build_causal():
    df = load_causal()
    NUM["causal_configs"] = sorted(df.dataset.unique().tolist())
    NUM["causal_seeds"] = sorted(df.seed.unique().tolist())
    overall = agg_table(df)
    lin = agg_table(df, "linear")
    non = agg_table(df, "nonlinear")

    methods = [m for m in ORDER if m in overall.index]
    lines = []
    lines.append("% auto-generated by scripts/build_results.py")
    lines.append("\\begin{tabular}{l cc cc c}")
    lines.append("\\toprule")
    lines.append(" & \\multicolumn{2}{c}{\\textbf{Non-linear}} & "
                 "\\multicolumn{2}{c}{\\textbf{Linear}} & \\textbf{All} \\\\")
    lines.append("\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\\cmidrule(lr){6-6}")
    lines.append("\\textbf{Method} & AUROC & F1 & AUROC & F1 & AUPRC \\\\")
    lines.append("\\midrule")
    for m in methods:
        nn = non.loc[m] if m in non.index else None
        ll = lin.loc[m] if m in lin.index else None
        ov = overall.loc[m]
        label = "\\textbf{CD-KAN (ours)}" if m == "CD-KAN" else m
        def cell(row, col):
            return "--" if row is None else f"{row[col]:.3f}"
        lines.append(
            f"{label} & {cell(nn,'aum')} & {cell(nn,'f1m')} & "
            f"{cell(ll,'aum')} & {cell(ll,'f1m')} & {ov['apm']:.3f} \\\\")
    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    with open(os.path.join(FIG, "tab_causal.tex"), "w") as f:
        f.write("\n".join(lines))

    # headline numbers
    for scope, tbl in [("all", overall), ("nonlinear", non), ("linear", lin)]:
        NUM[f"causal_{scope}"] = {
            m: dict(f1=round(float(tbl.loc[m, "f1m"]), 3),
                    auroc=round(float(tbl.loc[m, "aum"]), 3),
                    auprc=round(float(tbl.loc[m, "apm"]), 3),
                    shd=round(float(tbl.loc[m, "shdm"]), 2),
                    time=round(float(tbl.loc[m, "tm"]), 2))
            for m in tbl.index}

    # comprehensive figure: AUROC by regime + runtime
    fig, ax = plt.subplots(1, 3, figsize=(16, 4.6))
    for a, (title, tbl) in zip(ax[:2], [("Non-linear SCM", non), ("Linear VAR", lin)]):
        ms = [m for m in ORDER if m in tbl.index]
        vals = [tbl.loc[m, "aum"] for m in ms]
        colors = ["#d73027" if m == "CD-KAN" else "#4575b4" for m in ms]
        a.barh(range(len(ms)), vals, color=colors)
        a.set_yticks(range(len(ms))); a.set_yticklabels(ms)
        a.invert_yaxis(); a.set_xlim(0, 1.05); a.set_xlabel("AUROC")
        a.set_title(title, fontweight="bold"); a.axvline(0.5, color="grey", ls=":")
    ms = [m for m in ORDER if m in overall.index]
    tvals = [max(overall.loc[m, "tm"], 1e-3) for m in ms]
    a = ax[2]
    a.barh(range(len(ms)), tvals,
           color=["#d73027" if m == "CD-KAN" else "#999999" for m in ms])
    a.set_yticks(range(len(ms))); a.set_yticklabels(ms); a.invert_yaxis()
    a.set_xscale("log"); a.set_xlabel("mean fit time (s, log)")
    a.set_title("Runtime", fontweight="bold")
    plt.tight_layout()
    plt.savefig(os.path.join(FIG, "cdkan_sota_comprehensive_results.png"),
                dpi=200, bbox_inches="tight")
    plt.close()

    # heatmap: method x dataset AUROC
    piv = df.pivot_table(index="method", values="auroc", columns="dataset")
    piv = piv.reindex([m for m in ORDER if m in piv.index])
    fig, a = plt.subplots(figsize=(1.6 * len(piv.columns) + 3, 0.5 * len(piv) + 2))
    im = a.imshow(piv.values, cmap="RdYlGn", vmin=0.3, vmax=1.0, aspect="auto")
    a.set_xticks(range(len(piv.columns))); a.set_xticklabels(piv.columns, rotation=35, ha="right")
    a.set_yticks(range(len(piv.index))); a.set_yticklabels(piv.index)
    for i in range(len(piv.index)):
        for j in range(len(piv.columns)):
            v = piv.values[i, j]
            if not np.isnan(v):
                a.text(j, i, f"{v:.2f}", ha="center", va="center", fontsize=8)
    plt.colorbar(im, ax=a, label="AUROC")
    a.set_title("Causal discovery AUROC by method and dataset", fontweight="bold")
    plt.tight_layout()
    plt.savefig(os.path.join(FIG, "cdkan_sota_heatmap.png"), dpi=200, bbox_inches="tight")
    plt.close()


def build_stats():
    p = os.path.join(RES, "honest_causal_stats.csv")
    if not os.path.exists(p):
        return
    s = pd.read_csv(p)
    lines = ["% auto-generated", "\\begin{tabular}{l c c c c}", "\\toprule",
             "\\textbf{Baseline} & $n$ pairs & CD-KAN F1 & Baseline F1 & Wilcoxon $p$ \\\\",
             "\\midrule"]
    for _, r in s.iterrows():
        pv = r["p_value"]
        pv_s = "n/a" if pd.isna(pv) else (f"{pv:.3f}" if pv >= 0.001 else "$<$0.001")
        lines.append(f"{r['baseline']} & {int(r['n_pairs'])} & {r['cdkan_mean']:.3f} "
                     f"& {r['base_mean']:.3f} & {pv_s} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    with open(os.path.join(FIG, "tab_causal_stats.tex"), "w") as f:
        f.write("\n".join(lines))
    NUM["causal_stats"] = s.to_dict(orient="records")


def build_forecast():
    p = os.path.join(RES, "honest_forecast_agg.csv")
    if not os.path.exists(p):
        return
    df = pd.read_csv(p).sort_values("mse_mean")
    lines = ["% auto-generated", "\\begin{tabular}{l cc}", "\\toprule",
             "\\textbf{Model} & MSE $\\downarrow$ & MAE $\\downarrow$ \\\\", "\\midrule"]
    for _, r in df.iterrows():
        label = "\\textbf{CD-KAN (ours)}" if r["model"] == "CD-KAN" else r["model"]
        lines.append(f"{label} & {fmt(r['mse_mean'], r['mse_std'])} & "
                     f"{fmt(r['mae_mean'], r['mae_std'])} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    with open(os.path.join(FIG, "tab_forecast.tex"), "w") as f:
        f.write("\n".join(lines))
    NUM["forecast"] = df.set_index("model").round(4).to_dict(orient="index")
    lk = os.path.join(RES, "honest_forecast_leak.csv")
    if os.path.exists(lk):
        NUM["forecast_leak"] = pd.read_csv(lk).round(5).to_dict(orient="records")


def build_scale():
    """CD-KAN params + fit time vs d, from causal raw (+ optional timing sweep)."""
    df = pd.read_csv(os.path.join(RES, "honest_causal_raw.csv"))
    ck = df[df.method == "CD-KAN"].copy()
    if ck.empty:
        return
    g = ck.groupby("d").agg(params=("n_params", "max"),
                            t=("time_s", "mean")).reset_index()
    rows_by_d = {int(r["d"]): (int(r["params"]), float(r["t"])) for _, r in g.iterrows()}
    extra = os.path.join(RES, "scalability_sweep.csv")
    if os.path.exists(extra):
        for _, r in pd.read_csv(extra).iterrows():
            d = int(r["d"])
            if d not in rows_by_d:            # don't duplicate d already benchmarked
                rows_by_d[d] = (int(r["params"]), float(r["fit_time_s"]))
    lines = ["% auto-generated", "\\begin{tabular}{c c c}", "\\toprule",
             "$d$ & \\# parameters & mean fit time (s) \\\\", "\\midrule"]
    for d in sorted(rows_by_d):
        p, t = rows_by_d[d]
        lines.append(f"{d} & {p:,} & {t:.1f} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    with open(os.path.join(FIG, "tab_scale.tex"), "w") as f:
        f.write("\n".join(lines))
    NUM["scale"] = g.round(2).to_dict(orient="records")


def build_leak():
    p = os.path.join(RES, "honest_forecast_leak.csv")
    if not os.path.exists(p):
        return
    d = pd.read_csv(p)
    lab = {"global_leak": "Global normalization (test leaks in)",
           "train_only": "Train-only normalization (correct)"}
    lines = ["% auto-generated", "\\begin{tabular}{l cc}", "\\toprule",
             "\\textbf{Normalization} & MSE & MAE \\\\", "\\midrule"]
    for _, r in d.iterrows():
        lines.append(f"{lab.get(r['scaling'], r['scaling'])} & {r['mse']:.5f} & {r['mae']:.5f} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    with open(os.path.join(FIG, "tab_leak.tex"), "w") as f:
        f.write("\n".join(lines))


def build_sensitivity():
    p = os.path.join(RES, "sensitivity_v2.csv")
    if not os.path.exists(p):
        return
    d = pd.read_csv(p)
    lines = ["% auto-generated", "\\begin{tabular}{cc ccc}", "\\toprule",
             "$\\lambda_g$ & $G$ & AUROC $\\uparrow$ & F1 $\\uparrow$ & val MSE \\\\",
             "\\midrule"]
    for _, r in d.iterrows():
        lines.append(f"{r['lambda_g']:.3f} & {int(r['grid_size'])} & {r['auroc']:.3f} & "
                     f"{r['f1']:.3f} & {r['val_mse']:.3f} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    with open(os.path.join(FIG, "tab_sensitivity.tex"), "w") as f:
        f.write("\n".join(lines))
    NUM["sensitivity"] = d.round(3).to_dict(orient="records")


def build_ablation():
    p = os.path.join(RES, "ablation_results.csv")
    if not os.path.exists(p):
        # write a placeholder so LaTeX still compiles
        with open(os.path.join(FIG, "tab_ablation.tex"), "w") as f:
            f.write("\\begin{tabular}{lcc}\\toprule Configuration & AUROC & F1 \\\\"
                    "\\midrule \\multicolumn{3}{c}{(pending run)} \\\\\\bottomrule\\end{tabular}")
        return
    d = pd.read_csv(p)
    lines = ["% auto-generated", "\\begin{tabular}{l cc}", "\\toprule",
             "\\textbf{Configuration} & AUROC $\\uparrow$ & F1 $\\uparrow$ \\\\", "\\midrule"]
    for _, r in d.iterrows():
        label = "\\textbf{CD-KAN (full)}" if r["config"] == "full" else r["config"]
        lines.append(f"{label} & {r['auroc']:.3f} & {r['f1']:.3f} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    with open(os.path.join(FIG, "tab_ablation.tex"), "w") as f:
        f.write("\n".join(lines))
    NUM["ablation"] = d.round(3).to_dict(orient="records")


if __name__ == "__main__":
    build_causal()
    build_stats()
    build_forecast()
    build_scale()
    build_leak()
    build_sensitivity()
    build_ablation()
    # stability significance
    sp = os.path.join(RES, "stability_significance.csv")
    if os.path.exists(sp):
        NUM["stability"] = pd.read_csv(sp).to_dict(orient="records")[0]
    with open(os.path.join(RES, "NUMBERS.json"), "w") as f:
        json.dump(NUM, f, indent=2)
    print(json.dumps(NUM, indent=2))
