def tests(col, a, b, label):
    rows = []; ps = []
    for c, dd, n, no, m in CELLS:
        w = wide(col, c)
        if len(w) == 0 or a not in w or b not in w: continue
        x = (w[a] - w[b]).values; p = wil(x); lo, hi = boot_ci(x); mlo, mhi = boot_ci(x, np.median)
        sd = x.std(ddof=1) if len(x) > 1 else np.nan
        rows.append(dict(cell=c, k=len(x), mean_diff=f'{x.mean():+.3f}', CI95=f'[{lo:+.3f},{hi:+.3f}]', median_diff=f'{np.median(x):+.3f}', median_CI=f'[{mlo:+.3f},{mhi:+.3f}]',
                         wilcoxon_p=p, rank_biserial=round(rbc(x), 2), dz=round(x.mean() / sd, 2) if sd and sd > 0 else np.nan, n_a_better=int((x < 0).sum()), _t=(c != 'C8')))
        ps.append(p)
    R = pd.DataFrame(rows)
    if len(R):
        idx = R.index[R._t]; adj = pd.Series(np.nan, index=R.index); adj[idx] = holm(R.loc[idx, 'wilcoxon_p'].fillna(1).values); R['holm_p(C1-C7)'] = adj
        R['wilcoxon_p'] = R.wilcoxon_p.map(lambda v: f'{v:.4f}'); R['holm_p(C1-C7)'] = R['holm_p(C1-C7)'].map(lambda v: '' if pd.isna(v) else f'{v:.4f}'); R = R.drop(columns='_t')
    P(f'## {label}: {a} minus {b} (negative = {a} better where lower is better)\n'); P(md(R)); P('')
    return R
