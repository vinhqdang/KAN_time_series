rng = np.random.RandomState(0); B = 10000
def boot_ci(x, f=np.mean):
    x = np.asarray(x, float); bs = [f(x[rng.randint(0, len(x), len(x))]) for _ in range(B)]; return np.percentile(bs, [2.5, 97.5])
def wide(col, cell): return d[d.cell == cell].pivot(index='seed', columns='M', values=col).dropna()
def wil(x):
    x = np.asarray(x); 
    if np.all(x == 0) or len(x) < 2: return np.nan
    return stats.wilcoxon(x, method='exact' if len(x) <= 25 and not (x == 0).any() else 'auto').pvalue
def rbc(x):  # matched-pairs rank-biserial (negative = first method lower)
    x = np.asarray(x); x = x[x != 0]
    if len(x) == 0: return np.nan
    r = stats.rankdata(np.abs(x)); return (r[x > 0].sum() - r[x < 0].sum()) / r.sum()
def holm(p):
    p = np.asarray(p, float); o = np.argsort(p); m = len(p); adj = np.empty(m); run = 0
    for i, k in enumerate(o): run = max(run, (m - i) * p[k]); adj[k] = min(1, run)
    return adj
