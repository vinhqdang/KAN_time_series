"""Aggregate replication2 results -> results/all.csv, results/analysis.md (tests per PLAN.md)."""
import glob, os, numpy as np, pandas as pd
from scipy import stats
HERE = os.path.dirname(os.path.abspath(__file__)); os.chdir(HERE)
CELLS = [('unif', 3000), ('laplace', 3100), ('hetero', 3200)]
NAME = {'SSC': 'SSC', 'SSA': 'SSA', 'SSR_k1.5': 'SSR', 'BASILWs': 'BASIL-W'}
d = pd.concat([pd.read_csv(f) for f in sorted(glob.glob('results/d*_s*.csv'))], ignore_index=True)
d['M'] = d.method.map(NAME); d.to_csv('results/all.csv', index=False)
rng = np.random.RandomState(0); B = 10000
def wide(col, cell): return d[d.noise == cell].pivot(index='seed', columns='M', values=col)
def wil(x):
    x = np.asarray(x); x = x[x != 0]
    if len(x) < 2: return np.nan
    return stats.wilcoxon(x, method='exact' if len(x) <= 25 else 'approx').pvalue
def rbc(x):
    x = np.asarray(x); x = x[x != 0]
    if len(x) == 0: return np.nan
    r = stats.rankdata(np.abs(x)); return (r[x > 0].sum() - r[x < 0].sum()) / r.sum()
def bci(x):
    x = np.asarray(x, float); idx = rng.randint(0, len(x), (B, len(x))); return np.percentile(x[idx].mean(1), [2.5, 97.5])
def holm(p):
    p = np.asarray(p, float); o = np.argsort(p); m = len(p); adj = np.empty(m); run = 0
    for i, k in enumerate(o): run = max(run, (m - i) * p[k]); adj[k] = min(1, run)
    return adj
def md(df): return df.to_markdown(index=False)
out = []; P = out.append
P('# Replication2 analysis (auto-generated by aggregate.py)\n')
P('Datasets completed per cell and method:\n'); P(d.groupby(['noise', 'M']).seed.nunique().unstack().to_markdown()); P('')
met = ['nrmse', 'slope', 'auroc', 'auprc', 'orient', 'do_direct', 'do_indirect', 'cover', 'ece', 't_cost']
rows = []
for c, _ in CELLS:
    for M in NAME.values():
        h = d[(d.noise == c) & (d.M == M)]
        if not len(h): continue
        r = dict(cell=c, method=M, k=len(h))
        for k in met:
            v = h[k].dropna()
            if len(v): r[k] = f'{v.mean():.3f}' if k != 't_cost' else f'{v.median():.0f}'
        r['nrmse sd'] = f'{h.nrmse.std():.3f}'; r['nrmse range'] = f'{h.nrmse.min():.3f}-{h.nrmse.max():.3f}'
        r['do_ind max'] = f'{h.do_indirect.max():.2f}'; rows.append(r)
P('## Per-cell means (t_cost = median seconds)\n'); P(md(pd.DataFrame(rows))); P('')
# pairwise table
PAIRS = [('BASIL-W', 'SSC'), ('BASIL-W', 'SSA'), ('SSA', 'SSC'), ('BASIL-W', 'SSR'), ('SSA', 'SSR'), ('SSR', 'SSC')]
res = []
for col in ['nrmse', 'do_direct', 'do_indirect', 'auroc', 'orient']:
    for c, _ in CELLS:
        w = wide(col, c)
        for a, b in PAIRS:
            if a not in w or b not in w: continue
            z = (w[a] - w[b]).dropna().values
            if len(z) < 3: continue
            lo, hi = bci(z)
            res.append(dict(metric=col, cell=c, a=a, b=b, k=len(z), diff=z.mean(), lo=lo, hi=hi, p=wil(z), dz=z.mean() / z.std(ddof=1) if z.std() > 0 else np.nan,
                            rbc=rbc(z), a_lower=int((z < 0).sum()), b_lower=int((z > 0).sum()), tie=int((z == 0).sum())))
R = pd.DataFrame(res)
R['fam'] = np.where(R.b.eq('SSR') | R.a.eq('SSR'), 'secondary', 'primary')
R['p_holm'] = np.nan
for (m, f), g in R.groupby(['metric', 'fam']): R.loc[g.index, 'p_holm'] = holm(g.p.fillna(1).values)
R.to_csv('results/pairwise.csv', index=False)
for col in ['nrmse', 'do_direct', 'do_indirect', 'auroc', 'orient']:
    g = R[R.metric == col].copy()
    for k in ['diff', 'lo', 'hi', 'dz', 'rbc']: g[k] = g[k].map(lambda v: f'{v:+.3f}')
    g['p'] = g.p.map(lambda v: f'{v:.2g}'); g['p_holm'] = g.p_holm.map(lambda v: f'{v:.2g}')
    P(f'## Paired differences: {col} (a minus b; a_lower = datasets where a has the lower value; Holm family = primary (BASIL-W/SSA/SSC pairs) and secondary (SSR pairs) separately)\n')
    P(md(g.drop(columns=['metric']))); P('')
# win count table (NRMSE)
wr = []
for c, _ in CELLS:
    w = wide('nrmse', c).dropna()
    if len(w) == 0: continue
    r = dict(cell=c, k=len(w)); rk = w.rank(axis=1)
    for M in w.columns: r[f'{M} best'] = int((rk[M] == 1).sum())
    for M in w.columns: r[f'{M} mean rank'] = round(rk[M].mean(), 2)
    wr.append(r)
P('## Per-dataset NRMSE: number of datasets where each method is best (of 4) and mean rank\n'); P(md(pd.DataFrame(wr))); P('')
# hypotheses
P('## Hypothesis checks\n'); H = []
for c, _ in CELLS:
    w = wide('nrmse', c).dropna()
    if not len(w): continue
    wa = wide('auroc', c).dropna(); dd = wide('do_direct', c).dropna(); di = wide('do_indirect', c).dropna(); tc = wide('t_cost', c).dropna()
    r = dict(cell=c, k=len(w))
    r['H1 BW<SSC'] = f"{int((w['BASIL-W'] < w['SSC']).sum())}/{len(w)}"
    z = (w['BASIL-W'] - w['SSA']).values; r['H2 gap SSA-BW'] = f'{-z.mean():.3f}'; r['H2 BW wins'] = f'{int((z < 0).sum())}/{len(z)}'
    rr = R[(R.metric == 'nrmse') & (R.cell == c) & (R.a == 'BASIL-W') & (R.b == 'SSA')].iloc[0]; r['H2 Holm p'] = f'{rr.p_holm:.2g}'
    r['H3 SSA-SSC auroc'] = f"{(wa['SSA'] - wa['SSC']).mean():+.4f}"; r['H3 BW-SSC auroc'] = f"{(wa['BASIL-W'] - wa['SSC']).mean():+.4f}"
    for nm, x in [('direct', dd), ('indirect', di)]:
        m = x.mean(); r[f'H4 {nm} BW/SSA/SSC'] = f"{m['BASIL-W']:.3f}/{m['SSA']:.3f}/{m['SSC']:.3f}"
        r[f'H4 {nm} ok'] = bool(m['BASIL-W'] <= m['SSA'] + 0.01 and m['SSA'] < m['SSC'])
    med = tc.median(); r['H5 cost x SSC (SSA/SSR/BW)'] = f"{med['SSA']/med['SSC']:.2f}/{med['SSR']/med['SSC']:.2f}/{med['BASIL-W']/med['SSC']:.2f}"
    H.append(r)
P(md(pd.DataFrame(H))); P('')
# pooled
w = pd.concat([wide('nrmse', c).dropna() for c, _ in CELLS])
if len(w):
    P('## Pooled over cells (exploratory; graphs independent across cells)\n')
    for a, b in [('BASIL-W', 'SSC'), ('BASIL-W', 'SSA'), ('SSA', 'SSC'), ('BASIL-W', 'SSR'), ('SSA', 'SSR')]:
        z = (w[a] - w[b]).values; lo, hi = bci(z); P(f'- NRMSE {a} - {b}: n={len(z)}, mean {z.mean():+.3f} [{lo:+.3f}, {hi:+.3f}], Wilcoxon p={wil(z):.2g}, {a} lower in {(z<0).sum()}/{len(z)}')
    P('')
# extras: bands, failures
bw = d[d.M == 'BASIL-W']
P('## BASIL-W calibration/coverage and failures\n')
P(bw.groupby('noise')[['cover', 'ece', 'recall', 'rhat' if 'rhat' in bw else 'gap']].mean().round(4).to_markdown()); P('')
P('Datasets with indirect do-NRMSE > 2: ' + ', '.join(f"{M}: {int((d[d.M==M].do_indirect > 2).sum())}" for M in NAME.values())); P('')
open('results/analysis.md', 'w').write('\n'.join(out)); print('\n'.join(out)[:300])
