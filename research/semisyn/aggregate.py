"""Aggregate results/ -> results/analysis.md (tables, paired tests, verdicts per PLAN.md)."""
import glob, os, sys, numpy as np, pandas as pd
from scipy.stats import wilcoxon
HERE = os.path.dirname(os.path.abspath(__file__)); R = os.path.join(HERE, "results")
df = pd.concat([pd.read_csv(f) for f in sorted(glob.glob(os.path.join(R, "d*_s*.csv")))], ignore_index=True)
ed = pd.concat([pd.read_csv(f) for f in sorted(glob.glob(os.path.join(R, "edges", "d*_s*.csv")))], ignore_index=True)
rng = np.random.RandomState(0); B = 10000
SETS = [(11, 2000, "boot"), (11, 2000, "gauss"), (11, 500, "boot"), (11, 500, "gauss"), (110, 2000, "boot")]
METH = ["SSC", "SPADE", "SSA", "SSR_k1.5", "SSR_k2.5", "BASILWs", "GAM-ridge", "NOTEARS-linear", "var-sortnregress", "var-sortnregress-raw"]
out = []; P = out.append


def sub(s): return df[(df.d == s[0]) & (df.n == s[1]) & (df.noise == s[2])]
def sname(s): return f"d={s[0]}, n={s[1]}, {s[2]}"


def paired(s, m1, m2, col):
    a = sub(s)[sub(s).method == m1].set_index("seed")[col]; b = sub(s)[sub(s).method == m2].set_index("seed")[col]
    j = a.index.intersection(b.index); a, b = a[j].dropna(), b[j].dropna(); j = a.index.intersection(b.index); a, b = a[j].values, b[j].values
    if len(a) < 3: return None
    dlt = a - b; bs = np.array([dlt[rng.randint(0, len(dlt), len(dlt))].mean() for _ in range(B)])
    ix = [rng.randint(0, len(a), len(a)) for _ in range(B)]; rat = np.array([a[i].mean() / b[i].mean() for i in ix]) if (b > 0).all() else np.array([np.nan])
    try: p = wilcoxon(a, b).pvalue if np.any(dlt != 0) else 1.0
    except Exception: p = np.nan
    return dict(n=len(a), m1=a.mean(), m2=b.mean(), diff=dlt.mean(), lo=np.percentile(bs, 2.5), hi=np.percentile(bs, 97.5), ratio=a.mean() / b.mean() if b.mean() else np.nan,
                rlo=np.nanpercentile(rat, 2.5), rhi=np.nanpercentile(rat, 97.5), p=p, wins=int((dlt < 0).sum()))


def holm(ps):
    ps = np.array(ps, float); o = np.argsort(ps); adj = np.empty(len(ps)); run = 0.0
    for r, i in enumerate(o): run = max(run, (len(ps) - r) * ps[i]); adj[i] = min(1, run)
    return adj


P("# Semi-synthetic Sachs benchmark: results (auto-generated by aggregate.py)\n")
P(f"Datasets per setting: " + ", ".join(f"{sname(s)}: {sub(s).seed.nunique()}" for s in SETS) + "\n")
cols = [("nrmse", "NRMSE"), ("slope", "slope"), ("curve_r2", "R2"), ("auroc", "AUROC"), ("auprc", "AUPRC"), ("orient", "orient"), ("do_direct", "do_dir"), ("do_indirect", "do_ind"), ("ece", "ECE"), ("cover", "cover"), ("time", "time_s")]
for s in SETS:
    d = sub(s)
    if d.empty: continue
    g = d.groupby("method")[[c for c, _ in cols]].mean().reindex([m for m in METH if m in set(d.method)])
    g.insert(0, "datasets", d.groupby("method").seed.nunique()); g.columns = ["datasets"] + [n for _, n in cols]
    P(f"## Means by method: {sname(s)}\n"); P(g.round(3).to_markdown()); P("")
# paired tests
PRIM = [("BASILWs", "SSC", "nrmse"), ("SSA", "BASILWs", "nrmse"), ("BASILWs", "SSC", "auroc")]
SEC = [("SSR_k1.5", "SSC", "nrmse"), ("SSA", "SSC", "nrmse"), ("BASILWs", "SSR_k1.5", "nrmse"), ("BASILWs", "SSR_k2.5", "nrmse"), ("SSA", "SSR_k1.5", "nrmse"), ("BASILWs", "GAM-ridge", "nrmse"),
       ("SSC", "SPADE", "nrmse"), ("SSC", "SPADE", "auroc"), ("BASILWs", "SSC", "do_direct"), ("BASILWs", "SSC", "do_indirect"), ("SSA", "SSC", "auroc"), ("SSR_k1.5", "SSC", "auroc"), ("BASILWs", "NOTEARS-linear", "auroc"), ("SSC", "NOTEARS-linear", "auroc"), ("SSC", "var-sortnregress", "auroc")]
res = {}
for fam, L in (("PRIMARY", PRIM), ("SECONDARY (exploratory)", SEC)):
    rows = []
    for s in SETS:
        for m1, m2, c in L:
            r = paired(s, m1, m2, c)
            if r: rows.append(dict(setting=sname(s), cmp=f"{m1} - {m2} [{c}]", **r)); res[(s, m1, m2, c)] = r
    t = pd.DataFrame(rows)
    if len(t): t["p_holm"] = holm(t.p.fillna(1).values)
    P(f"## Paired tests, {fam} (Holm within family; diff = first minus second; ratio = mean first / mean second)\n")
    P(t.round(4).to_markdown(index=False) if len(t) else "none"); P("")
# strata
SS = (ed.gt_amp >= 0.3); NL = (ed.gt_nonlin >= 0.3)
P("## Per-edge NRMSE by stratum (STRONG: gt_amp >= 0.3; WEAK: < 0.3; NONLINEAR: gt_nonlin >= 0.3; mean over edges then over datasets)\n")
rows = []
for s in SETS:
    e = ed[(ed.d == s[0]) & (ed.n == s[1]) & (ed.noise == s[2])]
    for m in METH:
        x = e[e.method == m]
        if x.empty: continue
        f = lambda mask: x[mask.loc[x.index]].groupby("seed").nrmse_e.mean().mean()
        sl = lambda mask: x[mask.loc[x.index]].groupby("seed").slope_e.mean().mean()
        rows.append(dict(setting=sname(s), method=m, all=x.groupby("seed").nrmse_e.mean().mean(), strong=f(SS), weak=f(~SS), nonlinear=f(NL), linear_like=f(~NL), slope_strong=sl(SS), share_edges_strong=SS[x.index].mean()))
st = pd.DataFrame(rows); P(st.round(3).to_markdown(index=False)); P("")
P("### BASILWs / SSC NRMSE ratio by stratum\n"); rr = []
for s in SETS:
    a = st[(st.setting == sname(s)) & (st.method == "BASILWs")]; b = st[(st.setting == sname(s)) & (st.method == "SSC")]
    if len(a) and len(b): rr.append(dict(setting=sname(s), all=a["all"].values[0] / b["all"].values[0], strong=a.strong.values[0] / b.strong.values[0], weak=a.weak.values[0] / b.weak.values[0], nonlinear=a.nonlinear.values[0] / b.nonlinear.values[0]))
P(pd.DataFrame(rr).round(3).to_markdown(index=False)); P("")
# per true edge (d=11 only), n=2000 boot: how often SSC / BASILW curve is non-trivial
e = ed[(ed.d == 11) & (ed.n == 2000) & (ed.noise == "boot") & ed.method.isin(["SSC", "BASILWs", "SSR_k2.5", "GAM-ridge"])]
if len(e):
    t = e.groupby(["c", "e", "method"]).agg(gt_amp=("gt_amp", "mean"), gt_nonlin=("gt_nonlin", "mean"), nrmse=("nrmse_e", "mean")).unstack("method"); t.columns = [f"{a}_{b}" if a == "nrmse" else a for a, b in t.columns]
    t = t.loc[:, ~t.columns.duplicated()]; P("## Per true edge, d=11 n=2000 boot (node indices as in data/sachs column order; mean over datasets)\n"); P(t.round(2).to_markdown()); P("")
# verdicts
P("## Verdicts against PLAN.md predictions (mechanical)\n"); V = []
c3 = []
for s in SETS:
    r = res.get((s, "BASILWs", "SSC", "nrmse"))
    if r: c3.append((s, r)); 
ag = [(s, r) for s, r in c3 if r["ratio"] <= 0.7 and r["rhi"] < 0.8]; dis = [(s, r) for s, r in c3 if r["rlo"] >= 0.9]
d11 = [(s, r) for s, r in c3 if s[0] == 11]; d110 = [(s, r) for s, r in c3 if s[0] == 110]
V.append(f"P3 BASIL-W/SSC NRMSE ratio: " + "; ".join(f"{sname(s)} {r['ratio']:.2f} [{r['rlo']:.2f},{r['rhi']:.2f}]" for s, r in c3)
         + f" -> agree cells {len(ag)} (d=11: {sum(1 for s, _ in ag if s[0] == 11)} of {len(d11)}), disagree cells {len(dis)}. Verdict: "
         + ("AGREEMENT" if sum(1 for s, _ in ag if s[0] == 11) >= 3 and (not d110 or any(s[0] == 110 for s, _ in ag)) else ("DISAGREEMENT" if len(dis) >= 2 else "PARTIAL")))
c4 = [(s, res[(s, "SSA", "BASILWs", "nrmse")]) for s in SETS if (s, "SSA", "BASILWs", "nrmse") in res]
V.append("P4 SSA - BASIL-W NRMSE: " + "; ".join(f"{sname(s)} {r['diff']:+.3f} [{r['lo']:+.3f},{r['hi']:+.3f}]" for s, r in c4) + f" -> cells with SSA <= BASIL-W - 0.02: {sum(1 for s, r in c4 if r['diff'] < -0.02)} (disagreement if >= 2); cells with gap > 0: {sum(1 for s, r in c4 if r['lo'] > 0)}")
c5 = [(s, res[(s, "BASILWs", "SSC", "auroc")]) for s in SETS if (s, "BASILWs", "SSC", "auroc") in res]
V.append("P5 BASIL-W - SSC AUROC: " + "; ".join(f"{sname(s)} {r['diff']:+.3f} [{r['lo']:+.3f},{r['hi']:+.3f}]" for s, r in c5) + f" -> cells within -0.03: {sum(1 for s, r in c5 if r['diff'] > -0.03)} of {len(c5)}")
c1 = [(s, res.get((s, "SSC", "SPADE", "nrmse")), res.get((s, "SSC", "SPADE", "auroc"))) for s in SETS if s[0] == 11]
V.append("P1 SSC vs plain SPADE (d=11): " + "; ".join(f"{sname(s)} dNRMSE {a['diff']:+.4f}, dAUROC {b['diff']:+.4f}" for s, a, b in c1 if a and b))
P("\n".join("- " + v for v in V)); P("")
