"""X1 ensembles (b) in-forest/in-tree (river model) and (c) layered DAG; exact L, S via x1_er.LS_from_edges.
In-tree: node v>0 flows into a random earlier node (uniform recursive: parent uniform; preferential: prop. to
(number of children + 1)). Galton-Watson Poisson(1) conditioned on size is generated by random Cayley tree (uniform
random labelled tree with random root, oriented to the root via Prufer decoding)."""
import sys, math
import numpy as np
import os as _os, sys as _sys; _sys.path.insert(0, _os.path.dirname(_os.path.abspath(__file__)))   # sibling modules also under python -I
from x1_er import LS_from_edges

def recursive_in_tree(p, rng, pref=False):
    ei = np.arange(1, p); ej = np.zeros(p - 1, dtype=np.int64)  # edge child -> parent (child flows into parent): tail=child
    if not pref:
        ej = np.array([rng.integers(0, v) for v in range(1, p)], dtype=np.int64)
    else:
        urn = [0]
        for v in range(1, p):
            q = urn[rng.integers(0, len(urn))]; ej[v - 1] = q; urn += [q, v]   # weight = children+1
    return ei.astype(np.int64), ej

def cayley_in_tree(p, rng):
    # uniform labelled tree via Prufer, root at node 0, orient edges towards the root (BFS)
    prufer = rng.integers(0, p, size=p - 2)
    deg = np.ones(p, dtype=np.int64); np.add.at(deg, prufer, 1)
    import heapq
    leaves = [i for i in range(p) if deg[i] == 1]; heapq.heapify(leaves)
    adj = [[] for _ in range(p)]
    for x in prufer:
        l = heapq.heappop(leaves); adj[l].append(x); adj[x].append(l)
        deg[x] -= 1
        if deg[x] == 1: heapq.heappush(leaves, x)
    a, b = heapq.heappop(leaves), heapq.heappop(leaves); adj[a].append(b); adj[b].append(a)
    par = -np.ones(p, dtype=np.int64); par[0] = 0; st = [0]
    while st:
        u = st.pop()
        for v in adj[u]:
            if par[v] < 0: par[v] = u; st.append(v)
    ei = np.arange(1, p); return ei.astype(np.int64), par[1:]

def layered(w, M, c, rng):
    ei, ej = [], []
    for l in range(M - 1):
        mask = rng.random((w, w)) < c / w
        a, b = np.nonzero(mask)
        ei.append(l * w + a); ej.append((l + 1) * w + b)
    return np.concatenate(ei).astype(np.int64), np.concatenate(ej).astype(np.int64)

def stat(name, p, gen, nseed, extra=None):
    Ls, Ss, pi1, mu = [], [], [], []
    for s in range(nseed):
        rng = np.random.default_rng(777 + s); ei, ej = gen(rng)
        r = LS_from_edges(p, ei, ej, True)
        Ls.append(r["L"]); Ss.append(r["S"])
        indeg = np.bincount(ej, minlength=p); pi1.append(np.mean(indeg == 1)); mu.append(len(ei) / p)
        # exact identity check for forests: L - S = n_1/(2|E_S|)
        if extra == "forest":
            ES = p + len(ei); assert abs((r["L"] - r["S"]) - np.sum(indeg == 1) / (2 * ES)) < 1e-12
    Ls, Ss = np.array(Ls), np.array(Ss); pi1 = np.mean(pi1); mu = np.mean(mu)
    msg = f"{name:28s} p={p:7d} L={Ls.mean():.5f}+-{Ls.std(ddof=1)/math.sqrt(nseed):.5f} S={Ss.mean():.5f}+-{Ss.std(ddof=1)/math.sqrt(nseed):.5f}  pi1={pi1:.4f} mu={mu:.4f}"
    if extra == "forest":
        msg += f" | pred L={0.5+mu/(2*(1+mu)):.5f} S={0.5+(mu-pi1)/(2*(1+mu)):.5f}"
    if isinstance(extra, float):  # layered: extra = c; tree-like prediction (w -> infinity, M fixed)
        msg += f" | pred L={0.5+mu/(2*(1+mu)):.5f} S_treelike={0.5+mu*(1-math.exp(-extra))/(2*(1+mu)):.5f}"
    print(msg, flush=True)

if __name__ == "__main__":
    p = 20000; n = 6
    stat("in-tree uniform recursive", p, lambda r: recursive_in_tree(p, r), n, "forest")
    stat("in-tree preferential", p, lambda r: recursive_in_tree(p, r, True), n, "forest")
    stat("in-tree Cayley (GW Poisson1)", p, lambda r: cayley_in_tree(p, r), n, "forest")
    for (w, M, c) in [(2000, 10, 1.0), (2000, 10, 2.0), (2000, 10, 4.0), (4000, 5, 2.0), (200, 100, 2.0), (50, 400, 2.0), (50, 400, 0.5)]:
        stat(f"layered w={w} M={M} c={c}", w * M, lambda r: layered(w, M, c, r), 4, c)
