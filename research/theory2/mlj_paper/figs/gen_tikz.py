def fig_start():
    p, S, T = 3, chain(3), 4
    names = "abc"
    b = []
    dx, dy = 1.05, 0.9
    # (a) fixed start
    x0 = 0.0
    cnt = rel_counts(p, S, T)
    co = coords(p, T, x0, 0, dx, dy)
    b.append(rf"\node[labb,anchor=west] at ({x0 - 0.8:.2f},0.95) {{(a) fixed start}};")
    for v in range(p):
        b.append(rf"\node[lab] at ({x0 - 0.55:.2f},{-v * dy:.2f}) {{${names[v]}$}};")
    for t in range(1, T + 1):
        b.append(rf"\node[lab] at ({co[(0, t)][0]:.2f},0.55) {{$t={t}$}};")
    b += draw_unrolled("f", p, S, T, co, lambda v, t: "nd", lambda v, t: str(cnt[(v, t)]),
                       lambda i, j, t: "ars" if cnt[(i, t)] < cnt[(j, t + 1)] else "ar")
    sv = srho(p, S, T)
    b.append(rf"\node[lab,align=center] at ({x0 + 1.55:.2f},-3.0) {{counts of relatives $\rho$ in the nodes;\\"
             rf"orange: edges the count orients ($\rho$ grows)\\$s_\rho={sv:.1f}$ at $T=4$ ($\to 0.7$ as $T$ grows)}};")
    # (b) burn-in
    B, Tw = 2, 4
    x1 = 6.1
    cntb = rel_counts(p, S, Tw, B=B)
    cob = coords(p, B + Tw, x1, 0, dx, dy)
    b.append(rf"\node[labb,anchor=west] at ({x1 - 0.8:.2f},0.95) {{(b) latent burn-in $B\ge\Delta=2$, window of $T=4$}};")
    for v in range(p):
        b.append(rf"\node[lab] at ({x1 - 0.55:.2f},{-v * dy:.2f}) {{${names[v]}$}};")
    b.append(r"\begin{scope}[on background layer]")
    b.append(rf"\fill[band] ({x1 - 0.35:.2f},-1.6) rectangle ({x1 + (B - 1) * dx + 0.35:.2f},0.4);")
    b.append(r"\end{scope}")
    b.append(rf"\node[lab] at ({x1 + (B - 1) * dx / 2:.2f},0.55) {{latent}}; ")
    for t in range(B + 1, B + Tw + 1):
        b.append(rf"\node[lab] at ({cob[(0, t)][0]:.2f},0.55) {{$t={t - B}$}};")
    b += draw_unrolled("g", p, S, B + Tw, cob,
                       lambda v, t: "ndl" if t <= B else "nd",
                       lambda v, t: "" if t <= B else str(cntb[(v, t - B)]),
                       lambda i, j, t: "arl" if t < B + 1 else ("ars" if cntb[(i, t - B)] < cntb[(j, t + 1 - B)] else "ar"))
    sb = srho(p, S, Tw, B=B)
    b.append(rf"\node[lab,align=center] at ({x1 + (B + Tw - 1) * dx / 2:.2f},-3.0) {{every window node has the same count (12);\\"
             rf"no edge is oriented: $s_\rho^W={sb:.1f}$ for every $T$}};")
    write("fig_start", b)


# --------------------------------------------------------------------------------------------- Fig 5 (chain sharpness)
def fig_sharp():
    p, S, Tw = 4, chain(4), 2
    D = delta(p, S)
    names = "0123"
    b = []
    dx, dy = 0.95, 0.8
    xs = [0.0, 6.2]
    for k, B in enumerate((D - 1, D)):
        x0 = xs[k]
        Tt = B + Tw
        nodes, edges = unrolled(p, S, Tt)
        anc, desc = anc_desc(nodes, edges)
        tgt = (p - 1, B + 1)  # last chain node at the first window slice
        A = anc[tgt]
        co = coords(p, Tt, x0, 0, dx, dy)
        title = rf"(\alph{{{k + 1}}}) $B=\Delta-1={B}$" if k == 0 else rf"(\alph{{{k + 1}}}) $B=\Delta={B}$"
        b.append(rf"\node[labb,anchor=west] at ({x0 - 0.7:.2f},0.95) {{{title.replace(chr(92) + 'alph{1}', 'a').replace(chr(92) + 'alph{2}', 'b')}}};")
        for v in range(p):
            b.append(rf"\node[lab] at ({x0 - 0.5:.2f},{-v * dy:.2f}) {{$v_{names[v]}$}};")
        b.append(r"\begin{scope}[on background layer]")
        b.append(rf"\fill[band] ({x0 + B * dx - 0.35:.2f},-{(p - 1) * dy + 0.4:.2f}) rectangle ({x0 + (Tt - 1) * dx + 0.35:.2f},0.4);")
        b.append(r"\end{scope}")
        b.append(rf"\node[lab] at ({x0 + (B + 0.5) * dx:.2f},0.6) {{window}};")

        def style(v, t):
            if (v, t) == tgt:
                return "ndr"
            if (v, t) in A:
                return "ndh"
            return "ndl" if t <= B else "nd"

        b += draw_unrolled("s" + str(k), p, S, Tt, co, style, lambda v, t: "",
                           lambda i, j, t: "arb" if ((i, t) in A and (j, t + 1) in A) else "arl")
        shared = [(v, t) for (v, t) in A if v == 0]
        if shared:
            v, t = shared[0]
            b.append(rf"\node[draw=cOrange,line width=1.4pt,circle,minimum size=0.55cm,inner sep=0pt] at ({co[(v, t)][0]:.2f},{co[(v, t)][1]:.2f}) {{}};")
            msg = r"$v_0$ at $t=1$ (ringed) is an ancestor of\\the orange node and of every window $v_0$:\\the window nodes $v_0$ and $v_3$ are relatives"
        else:
            msg = r"no $v_0$ node is an ancestor of\\the orange node: the window nodes\\$v_0$ and $v_3$ are not relatives"
        b.append(rf"\node[lab,align=center] at ({x0 + (Tt - 1) * dx / 2:.2f},-{(p - 1) * dy + 1.0:.2f}) {{{msg}}};")
    write("fig_sharp", b)


# --------------------------------------------------------------------------------------------- Fig 8 (identifiability)
def fig_ident():
    p, S = 3, chain(3)
    names = "abc"
    b = []
    dx, dy = 0.98, 0.8
    T = 3
    # (a) slice = height
    x0 = 0.0
    co = coords(p, T, x0, 0, dx, dy)
    b.append(rf"\node[labb,anchor=west] at ({x0 - 0.3:.2f},1.0) {{(a) slice = height}};")
    nodes, edges = unrolled(p, S, T)
    hgt = {n: 1 for n in nodes}   # height = 1 + number of edges of a longest directed path ending in the node
    for _ in range(len(nodes)):
        for u, v in edges:
            hgt[v] = max(hgt[v], hgt[u] + 1)
    shade = {1: 10, 2: 28, 3: 46}
    for (v, t), (x, y) in co.items():
        b.append(rf"\node[nd,fill=cBlue!{shade[hgt[(v, t)]]}] (h{v}x{t}) at ({x:.2f},{y:.2f}) {{{hgt[(v, t)]}}};")
    for (u, w) in edges:
        b.append(rf"\draw[ar] (h{u[0]}x{u[1]}) -- (h{w[0]}x{w[1]});")
    b.append(rf"\node[lab,align=center,text width=3.3cm] at ({x0 + dx:.2f},-2.5) {{numbers: height of the node in $G_T$; it equals the slice $t$}};")
    # (b) CPDAG
    x1 = 3.9
    co = coords(p, T, x1, 0, dx, dy)
    b.append(rf"\node[labb,anchor=west] at ({x1 - 0.5:.2f},1.0) {{(b) equivalence class}};")
    for v in range(p):
        b.append(rf"\node[lab] at ({x1 - 0.55:.2f},{-v * dy:.2f}) {{${names[v]}$}};")
    for (v, t), (x, y) in co.items():
        b.append(rf"\node[nd] (c{v}x{t}) at ({x:.2f},{y:.2f}) {{}};")
    for t in range(1, T):
        for (i, j) in with_loops(p, S):
            und = (i == j == 0)  # self-chain of the loop-only unit a
            b.append(rf"\draw[{'un' if und else 'ar'}] (c{i}x{t}) -- (c{j}x{t + 1});")
    b.append(rf"\node[lab,align=center,text width=3.6cm] at ({x1 + dx:.2f},-2.5) {{only the self-chain of the loop-only unit $a$ is undirected: $T^{{m_0}}=3$ equivalent graphs}};")
    # (c) T = 2 counterexample
    x2 = 8.3
    b.append(rf"\node[labb,anchor=west] at ({x2 - 0.3:.2f},1.0) {{(c) $T=2$, free start}};")
    ids = {"al": "$\\alpha$", "be": "$\\beta$", "ga": "$\\gamma$", "de": "$\\delta$"}
    for k, (xx, s1, s2, E) in enumerate((
            (x2, ("al", "be"), ("ga", "de"), [("al", "ga"), ("al", "de"), ("be", "de")]),
            (x2 + 2.45, ("al", "de"), ("ga", "be"), [("al", "ga"), ("al", "be"), ("de", "be")]))):
        pos = {s1[0]: (xx, 0.0), s1[1]: (xx, -dy), s2[0]: (xx + 1.05, 0.0), s2[1]: (xx + 1.05, -dy)}
        for nid, (x, y) in pos.items():
            b.append(rf"\node[nd] ({nid}{k}) at ({x:.2f},{y:.2f}) {{{ids[nid]}}};")
        for (u, w) in E:
            b.append(rf"\draw[ar] ({u}{k}) -- ({w}{k});")
        b.append(rf"\node[lab] at ({xx:.2f},0.5) {{slice 1}}; \node[lab] at ({xx + 1.05:.2f},0.5) {{slice 2}};")
        b.append(rf"\node[lab] at ({xx + 0.52:.2f},-1.38) {{{'true' if k == 0 else 'alternative'}}};")
    b.append(rf"\node[lab,align=center,text width=4.4cm] at ({x2 + 1.6:.2f},-2.5) {{same four columns, same number of edges, different column DAG, same law}};")
    write("fig_ident", b)


