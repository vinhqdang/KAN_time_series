    cnt = rel_counts(p, S, T)
    nodes, edges = unrolled(p, S, T)
    rel = relatives(nodes, edges)
    target = (2, 2)  # c_2
    R = rel[target]
    b = []
    # (a) summary graph
    b.append(r"\node[labb,anchor=west] at (-0.35,1.35) {(a) summary graph};")
    b += summary_graph("s", p, S, {0: (0, 0), 1: (1.1, 0), 2: (2.2, 0)})
    b.append(r"\node[lab,align=center,text width=3.0cm] at (1.1,-0.95) {self-loop at every node;\\summary edges $a\to b\to c$};")
    # (b) unrolled DAG
    x0, dxb = 3.9, 1.08
    co = coords(p, T, x0, 0.55, dxb, 0.95)
    b.append(rf"\node[labb,anchor=west] at ({x0 - 0.45:.2f},1.35) {{(b) unrolled DAG, $T=4$}};")
    for t in range(1, T + 1):
        b.append(rf"\node[lab] at ({co[(0, t)][0]:.2f},0.98) {{$t={t}$}};")
    b.append(r"\begin{scope}[on background layer]")
    b.append(rf"\fill[band] ({x0 - 0.35:.2f},-1.75) rectangle ({x0 + 3 * dxb + 0.35:.2f},0.88);")
    b.append(r"\end{scope}")
    b += draw_unrolled("u", p, S, T, co,
                       lambda v, t: "ndr" if (v, t) == target else ("ndh" if (v, t) in R else "nd"),
                       sub, lambda i, j, t: "ar")
    b.append(rf"\node[lab,align=center,text width=4.3cm] at ({x0 + 1.5 * dxb:.2f},-2.4) "
             rf"{{blue: the {len(R)} relatives of $c_2$ (orange); they share an ancestor with it}};")
    # (c) label-free view
    x1, dxc = 8.6, 0.8
    b.append(rf"\node[labb,anchor=west] at ({x1 - 0.3:.2f},1.35) {{(c) what the learner sees}};")
    order = [(0, 3), (2, 1), (1, 2), (2, 4), (0, 1), (1, 4), (2, 3), (0, 4), (1, 1), (0, 2), (2, 2), (1, 3)]
    slots = [(i % 4, i // 4) for i in range(12)]
    for (v, t), (cx, cy) in zip(order, slots):
        x, y = x1 + cx * dxc, 0.55 - cy * 0.95
        b.append(rf"\node[ndu] at ({x:.2f},{y:.2f}) {{{cnt[(v, t)]}}};")
    b.append(rf"\node[lab,align=center,text width=3.6cm] at ({x1 + 1.5 * dxc:.2f},-2.4) "
             rf"{{labels erased, columns shuffled; each circle shows its number of relatives $\rho$}};")
