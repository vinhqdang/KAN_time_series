"""Generate the TikZ pictures of the schematic figures (written to figs/tikz/*.tex, one tikzpicture each).

All counts (relatives, heights, ancestors, Delta) are computed here from the unrolled graph by enumeration
(unroll.py), not typed by hand.  Styles live in tikzstyle.tex.
Run:  python3 gen_tikz.py          (pure Python 3, no third-party packages)
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from unroll import (unrolled, anc_desc, relatives, rel_counts, with_loops, chain, ring, intree, outtree, delta, srho,
                    dist_matrix)

OUT = os.path.join(HERE, "tikz")
os.makedirs(OUT, exist_ok=True)
L = "abcdefgh"


def coords(p, T, x0, y0, dx, dy, t0=1):
    return {(v, t): (x0 + (t - t0) * dx, y0 - v * dy) for v in range(p) for t in range(t0, t0 + T)}


def nname(pre, v, t):
    return f"{pre}{v}x{t + 10}"  # +10 keeps names alphanumeric for non-positive slice indices


def draw_unrolled(pre, p, S, T, co, nstyle, label, estyle, t0=1):
    lines = []
    for (v, t), (x, y) in co.items():
        lines.append(rf"\node[{nstyle(v, t)}] ({nname(pre, v, t)}) at ({x:.3f},{y:.3f}) {{{label(v, t)}}};")
    for t in range(t0, t0 + T - 1):
        for (i, j) in with_loops(p, S):
            lines.append(rf"\draw[{estyle(i, j, t)}] ({nname(pre, i, t)}) -- ({nname(pre, j, t + 1)});")
    return lines


def write(name, body):
    with open(os.path.join(OUT, name + ".tex"), "w") as f:
        f.write("% generated by gen_tikz.py -- do not edit by hand\n\\begin{tikzpicture}[>=Stealth]\n")
        f.write("\n".join(body))
        f.write("\n\\end{tikzpicture}\n")


def sub(v, t):
    return f"${L[v]}_{{{t}}}$"


def summary_graph(pre, p, S, pos, loops=True, sty="nd", names=None):
    lines = []
    for v in range(p):
        x, y = pos[v]
        lines.append(rf"\node[{sty}] ({pre}{v}) at ({x:.3f},{y:.3f}) {{{names[v] if names else L[v]}}};")
    for (i, j) in S:
        if i != j:
            lines.append(rf"\draw[ar] ({pre}{i}) -- ({pre}{j});")
    if loops:
        for v in range(p):
            lines.append(rf"\path ({pre}{v}) edge[ar,loop above,looseness=7] ({pre}{v});")
    return lines


